export function translateTerm(text, lang) {
  if (!text || lang === "en") return text;
  if (TERM_DICT[text] && TERM_DICT[text][lang]) {
    return TERM_DICT[text][lang];
  }
  const stored = JSON.parse(localStorage.getItem("dynamic_translations") || "{}");
  if (stored[text] && stored[text][lang]) {
    return stored[text][lang];
  }
  return text;
}

export function translateDuration(durationStr, lang) {
  if (!durationStr || lang === "en") return durationStr;
  const unit = UNIT_MAP.Hours[lang] || "Hours";
  return durationStr.replace(/Hours/gi, unit);
}

export function translateMeta(key, lang) {
  if (lang === "en") return key;
  return (UNIT_MAP[key] && UNIT_MAP[key][lang]) || key;
}

export function saveDynamicTranslation(englishTitle, translationsMap = {}) {
  if (!englishTitle) return;
  const stored = JSON.parse(localStorage.getItem("dynamic_translations") || "{}");
  stored[englishTitle] = { ...(stored[englishTitle] || {}), ...translationsMap };
  localStorage.setItem("dynamic_translations", JSON.stringify(stored));
}

export function translateWithDynamic(text, lang, inlineTranslations = {}) {
  if (!text || lang === "en") return text;
  if (inlineTranslations && inlineTranslations[lang]) {
    return inlineTranslations[lang];
  }
  return translateTerm(text, lang);
}